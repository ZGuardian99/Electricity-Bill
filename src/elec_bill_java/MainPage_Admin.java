    private void loadCustomerData() {
        allCustomers = DBUtil.loadDetailsAdmin(); // fetch all data once
        totalPages = (int) Math.ceil(allCustomers.size() / (double) pageSize);
        updateTable();
    }

    private void updateTable() {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) Customers.getModel();
        model.setRowCount(0); // clear old data

        int start = (currentPage - 1) * pageSize;
        int end = Math.min(start + pageSize, allCustomers.size());

        for (int i = start; i < end; i++) {
            AdminShow c = allCustomers.get(i);
            model.addRow(new Object[]{
                c.getName(),
                c.getType(),
                c.getBillDate().plusDays(30)
            });
        }

        // Update page label
        jLabel1.setText("Page " + currentPage + " of " + totalPages);

        // Enable/disable buttons
        Prev.setEnabled(currentPage > 1);
        Next.setEnabled(currentPage < totalPages);
    }
