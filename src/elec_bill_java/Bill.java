    private void loadBill(){
        int units = rngUnits();
        
        if(DBUtil.isUnitSet(C_ID)){
            DBUtil.setUnit(units , C_ID);
        } else {
            DBUtil.updateUnit(units , C_ID);
        }
        this.UnitD.setText(units+"");
        
        if(DBUtil.doesCIdExist(C_ID)){
            this.DateD.setText(DBUtil.getDate1(C_ID).toString());
        } else {
            this.DateD.setText(DBUtil.getDate2(C_ID).toString());
        }
        
        setDays();
        
        this.MeterD.setText(DBUtil.getRate(C_ID)+"");
        amt = totalAmt(units, C_ID);
        this.AmtD.setText(amt+"");
    }
    
    private int rngUnits(){
        Random rand = new Random();
        return rand.nextInt(6) + 5;
    }
    
    private void setDays(){
        try {
            int days = DBUtil.getDays(C_ID);
            if(days > 30){
                this.O_DaysD.setText(days+" days");
            }
        } catch(SQLException e){
            
        }
    }
    
    private double totalAmt(int unit, int C_ID) {
        double amt = 0;

        try {
            int days = DBUtil.getDays(C_ID);
            double rate = DBUtil.getRate(C_ID);

            if (days <= 30) {
                amt = unit * rate * days;
            } else {
                double amt1 = unit * rate * 30;
                double amt2 = unit * rate * (days - 30);
                amt = amt1 + amt2;
            }
        } catch (SQLException ex) {
            System.out.println("Error fetching days or rate: " + ex.getMessage());
            ex.printStackTrace();
        }

        return amt;
    }
    
    private void loadPaymentMethods() {
        javax.swing.DefaultComboBoxModel<String> model = new javax.swing.DefaultComboBoxModel<>();
        model.addElement("Select Payment Method"); // default
        model.addElement("UPI");
        model.addElement("Card");
        model.addElement("Net Banking");
        PayS.setModel(model);
        Pay.setEnabled(false);
        PayS.addItemListener(e -> {
            if (e.getStateChange() == java.awt.event.ItemEvent.SELECTED) {
                Pay.setEnabled(PayS.getSelectedIndex() != 0);
            }
        });
    }
    
    
    
