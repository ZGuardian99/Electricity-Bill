    private void loadTransactions() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0); // clear existing rows

        String sql = """
            SELECT * FROM (
                SELECT b.BillDate, 
                       CONCAT(b.B_ID, LPAD(p.P_ID, 3, '0')) AS ID,
                       b.TotalAmt,
                       pm.Mode
                FROM bill b
                JOIN payment p ON b.B_ID = p.B_ID
                JOIN payment_mode pm ON p.ModeID = pm.ModeID
                WHERE b.C_ID = ?
                ORDER BY b.BillDate DESC
                LIMIT 12
            ) AS last12
            ORDER BY BillDate ASC;
        """;

        try (Connection conn = DBUtil.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {
            pstmt.setInt(1, C_ID);
            ResultSet rs = pstmt.executeQuery();

            while (rs.next()) {
                Object[] row = {
                    rs.getDate("BillDate"),
                    rs.getString("ID"),
                    rs.getDouble("TotalAmt"),
                    rs.getString("Mode")
                };
                model.addRow(row);
            }

        } catch (SQLException ex) {
            ex.printStackTrace();
        }
    }
