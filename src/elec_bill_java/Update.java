    private void UpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdateActionPerformed
        String name = NameE.getText().trim();
        String phone = PhoneNoE.getText().trim();
        String email = EmailE.getText().trim();
        String gender = (String) GenderE.getSelectedItem();
        String state = (String) StateE.getSelectedItem();
        String city = (String) CityE.getSelectedItem();
        String meter = (String) MeterE.getSelectedItem();
        String oldPasswordInput = new String(OldPasswordE.getPassword()).trim();
        String newPasswordInput = new String(NewPasswordE.getPassword()).trim();
        String address = Address.getText().trim();

        if (oldPasswordInput.isEmpty()) {
            Error.setText("Please enter your old password to update data.");
            return;
        }

        if (!isValidEmail(email)) {
            Error.setText("Please enter a valid email address.");
            return;
        }

        if (!isValidPhone(phone)) {
            Error.setText("Please enter a valid phone number (10 digits).");
            return;
        }

        try (Connection conn = DBUtil.getConnection()) {

            // ✅ Verify old password
            String fetchUser = "SELECT Password, Salt FROM customer WHERE C_ID=?";
            String storedHash = null, storedSalt = null;
            try (PreparedStatement ps = conn.prepareStatement(fetchUser)) {
                ps.setInt(1, C_ID);
                try (ResultSet rs = ps.executeQuery()) {
                    if (rs.next()) {
                        storedHash = rs.getString("Password");
                        storedSalt = rs.getString("Salt");
                    }
                }
            }

            if (storedHash == null || storedSalt == null) {
                Error.setText("User not found.");
                return;
            }

            String oldHash = DBUtil.hashPassword(oldPasswordInput, storedSalt);
            if (!oldHash.equals(storedHash)) {
                Error.setText("Old password is incorrect.");
                return;
            }

            // ✅ Check uniqueness but exclude current C_ID
            String checkQuery = "SELECT COUNT(*) FROM customer WHERE (EmailID = ? OR phoneno = ?) AND C_ID <> ?";
            try (PreparedStatement checkStmt = conn.prepareStatement(checkQuery)) {
                checkStmt.setString(1, email);
                checkStmt.setString(2, phone);
                checkStmt.setInt(3, C_ID);
                try (ResultSet rs = checkStmt.executeQuery()) {
                    if (rs.next() && rs.getInt(1) > 0) {
                        Error.setText("Email or Phone already exists!");
                        return;
                    }
                }
            }

            // ✅ Start building update
            String updateCustomer;
            if (!newPasswordInput.isEmpty()) {
                if (!isStrongPassword(newPasswordInput)) {
                    Error.setText("New password must be at least 8 characters with uppercase, lowercase, number, and special character.");
                    return;
                }

                // Hash new password
                String newSalt = DBUtil.generateSalt();
                String newHash = DBUtil.hashPassword(newPasswordInput, newSalt);

                updateCustomer = "UPDATE customer SET EmailID=?, Gender=?, name=?, Password=?, Salt=?, phoneno=? WHERE C_ID=?";
                try (PreparedStatement ps = conn.prepareStatement(updateCustomer)) {
                    ps.setString(1, email);
                    ps.setString(2, gender);
                    ps.setString(3, name);
                    ps.setString(4, newHash);
                    ps.setString(5, newSalt);
                    ps.setString(6, phone);
                    ps.setInt(7, C_ID);
                    ps.executeUpdate();
                }
            } else {
                // Don’t update password
                updateCustomer = "UPDATE customer SET EmailID=?, Gender=?, name=?, phoneno=? WHERE C_ID=?";
                try (PreparedStatement ps = conn.prepareStatement(updateCustomer)) {
                    ps.setString(1, email);
                    ps.setString(2, gender);
                    ps.setString(3, name);
                    ps.setString(4, phone);
                    ps.setInt(5, C_ID);
                    ps.executeUpdate();
                }
            }

            // ✅ Update address
            int cityID = getCityId(city, stateIdMap.get(state));
            String updateAddress = "UPDATE address SET CityID=?, AddressText=? WHERE C_ID=?";
            try (PreparedStatement ps = conn.prepareStatement(updateAddress)) {
                ps.setInt(1, cityID);
                ps.setString(2, address);
                ps.setInt(3, C_ID);
                ps.executeUpdate();
            }

            // ✅ Update meter type
            int rateID = getRateId(meter);
            String updateMeter = "UPDATE meter SET RateID=? WHERE C_ID=?";
            try (PreparedStatement ps = conn.prepareStatement(updateMeter)) {
                ps.setInt(1, rateID);
                ps.setInt(2, C_ID);
                ps.executeUpdate();
            }

            javax.swing.JOptionPane.showMessageDialog(this, 
                "Details updated successfully!", 
                "Update Successful", 
                javax.swing.JOptionPane.INFORMATION_MESSAGE);

            // Close current Update window
            this.dispose();

            // Open MainPage_Customer
            MainPage_Customer mainPage = new MainPage_Customer(C_ID);
            mainPage.setVisible(true);

        } catch (SQLException ex) {
            ex.printStackTrace();
            Error.setText("Database error: " + ex.getMessage());
        } catch (Exception ex) {
            ex.printStackTrace();
            Error.setText("Unexpected error occurred. Please try again.");
        }
    }//GEN-LAST:event_UpdateActionPerformed

